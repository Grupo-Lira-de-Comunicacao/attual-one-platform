create or replace function public.institutional_nodes_set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  if tg_op = 'INSERT' and new.created_by is null then new.created_by := auth.uid(); end if;
  return new;
end;
$$;

drop trigger if exists institutional_nodes_set_updated_at_trigger on public.institutional_nodes;
create trigger institutional_nodes_set_updated_at_trigger before insert or update on public.institutional_nodes for each row execute function public.institutional_nodes_set_updated_at();

create or replace function public.institutional_nodes_audit()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.institutional_change_log(node_id, action, before_data, after_data, actor_id) values (new.id, 'insert', null, to_jsonb(new), auth.uid());
    return new;
  elsif tg_op = 'UPDATE' then
    insert into public.institutional_change_log(node_id, action, before_data, after_data, actor_id) values (new.id, 'update', to_jsonb(old), to_jsonb(new), auth.uid());
    return new;
  elsif tg_op = 'DELETE' then
    insert into public.institutional_change_log(node_id, action, before_data, after_data, actor_id) values (old.id, 'delete', to_jsonb(old), null, auth.uid());
    return old;
  end if;
  return null;
end;
$$;

drop trigger if exists institutional_nodes_audit_trigger on public.institutional_nodes;
create trigger institutional_nodes_audit_trigger after insert or update or delete on public.institutional_nodes for each row execute function public.institutional_nodes_audit();

