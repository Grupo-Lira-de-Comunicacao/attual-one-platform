create table if not exists public.institutional_nodes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null check (length(trim(name)) > 0),
  node_type text not null check (node_type in ('group','pillar','brand','project','platform','system')),
  parent_id uuid null references public.institutional_nodes(id) on delete restrict,
  status text not null default 'active' check (status in ('active','planned','paused','archived')),
  display_order integer not null default 0 check (display_order >= 0),
  is_official boolean not null default true,
  description text null,
  responsible text null,
  website text null,
  instagram text null,
  created_by uuid null references auth.users(id),
  updated_by uuid null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint institutional_nodes_not_self_parent check (parent_id is null or parent_id <> id)
);

create index if not exists institutional_nodes_parent_order_idx on public.institutional_nodes(parent_id, display_order, name);

alter table public.institutional_nodes enable row level security;
grant select, insert, update, delete on table public.institutional_nodes to authenticated;
revoke all on table public.institutional_nodes from anon;

drop policy if exists "institutional_nodes_select_authenticated" on public.institutional_nodes;
create policy "institutional_nodes_select_authenticated" on public.institutional_nodes for select to authenticated using ((select auth.uid()) is not null);
drop policy if exists "institutional_nodes_insert_authenticated" on public.institutional_nodes;
create policy "institutional_nodes_insert_authenticated" on public.institutional_nodes for insert to authenticated with check ((select auth.uid()) is not null);
drop policy if exists "institutional_nodes_update_authenticated" on public.institutional_nodes;
create policy "institutional_nodes_update_authenticated" on public.institutional_nodes for update to authenticated using ((select auth.uid()) is not null) with check ((select auth.uid()) is not null);
drop policy if exists "institutional_nodes_delete_authenticated" on public.institutional_nodes;
create policy "institutional_nodes_delete_authenticated" on public.institutional_nodes for delete to authenticated using ((select auth.uid()) is not null);

create table if not exists public.institutional_change_log (
  id bigint generated by default as identity primary key,
  node_id uuid null,
  action text not null check (action in ('insert','update','delete')),
  before_data jsonb null,
  after_data jsonb null,
  actor_id uuid null references auth.users(id),
  occurred_at timestamptz not null default now()
);
create index if not exists institutional_change_log_occurred_idx on public.institutional_change_log(occurred_at desc);
alter table public.institutional_change_log enable row level security;
grant select, insert on table public.institutional_change_log to authenticated;
revoke update, delete on table public.institutional_change_log from authenticated;
revoke all on table public.institutional_change_log from anon;
drop policy if exists "institutional_change_log_select_authenticated" on public.institutional_change_log;
create policy "institutional_change_log_select_authenticated" on public.institutional_change_log for select to authenticated using ((select auth.uid()) is not null);
drop policy if exists "institutional_change_log_insert_authenticated" on public.institutional_change_log;
create policy "institutional_change_log_insert_authenticated" on public.institutional_change_log for insert to authenticated with check ((select auth.uid()) is not null and (actor_id is null or actor_id = (select auth.uid())));

create table if not exists public.institutional_versions (
